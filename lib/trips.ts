const TRIP_COLUMNS =
  'id, user_id, name, destination, start_date, end_date, traveling_on_document_id, created_at';
const ITEM_COLUMNS =
  'id, trip_id, user_id, type, provider, confirmation_number, source, file_path, external_link, item_date, amount_due, due_date, notes, created_at';
const CHECKLIST_COLUMNS =
  'id, trip_id, label, category, status, source, linked_trip_item_id, created_at';

async function currentUserId(): Promise<string> {
  const { data } = await supabase.auth.getUser();
  if (!data.user) throw new Error('You need to be logged in.');
  return data.user.id;
}

// --- trips -----------------------------------------------------------------

export async function listTrips(): Promise<Trip[]> {
  const { data, error } = await supabase
    .from('trips')
    .select(TRIP_COLUMNS)
    .order('start_date', { ascending: true, nullsFirst: false });
  if (error) throw new Error(error.message);
  return (data ?? []) as Trip[];
}

export async function getTrip(tripId: string): Promise<Trip | null> {
  const { data, error } = await supabase
    .from('trips')
    .select(TRIP_COLUMNS)
    .eq('id', tripId)
    .maybeSingle();
  if (error) throw new Error(error.message);
  return (data as Trip | null) ?? null;
}

export type TripInput = {
  name: string;
  destination?: string | null;
  startDate?: string | null;
  endDate?: string | null;
};

export async function createTrip(input: TripInput, attendeeIds: string[]): Promise<Trip> {
  const userId = await currentUserId();

  const { data, error } = await supabase
    .from('trips')
    .insert({
      user_id: userId,
      name: input.name.trim(),
      destination: input.destination?.trim() || null,
      start_date: input.startDate || null,
      end_date: input.endDate || null,
    })
    .select(TRIP_COLUMNS)
    .single();

  if (error) throw new Error(error.message);
  const trip = data as Trip;

  await setTripAttendees(trip.id, attendeeIds);
  await seedDefaultChecklist(trip.id);
  return trip;
}

export async function updateTrip(tripId: string, input: TripInput): Promise<Trip> {
  const { data, error } = await supabase
    .from('trips')
    .update({
      name: input.name.trim(),
      destination: input.destination?.trim() || null,
      start_date: input.startDate || null,
      end_date: input.endDate || null,
    })
    .eq('id', tripId)
    .select(TRIP_COLUMNS)
    .single();
  if (error) throw new Error(error.message);
  return data as Trip;
}

export async function deleteTrip(tripId: string): Promise<void> {
  const { error } = await supabase.from('trips').delete().eq('id', tripId);
  if (error) throw new Error(error.message);
}

// --- attendees -------------------------------------------------------------

export async function listTripAttendeeIds(tripId: string): Promise<string[]> {
  const { data, error } = await supabase
    .from('trip_travelers')
    .select('traveler_id')
    .eq('trip_id', tripId);
  if (error) throw new Error(error.message);
  return (data ?? []).map((r: { traveler_id: string }) => r.traveler_id);
}

/** Replace the attendee list wholesale — simpler than diffing, and the lists are tiny. */
export async function setTripAttendees(tripId: string, travelerIds: string[]): Promise<void> {
  const { error: delErr } = await supabase.from('trip_travelers').delete().eq('trip_id', tripId);
  if (delErr) throw new Error(delErr.message);

  if (travelerIds.length === 0) return;

  const { error } = await supabase
    .from('trip_travelers')
    .insert(travelerIds.map((traveler_id) => ({ trip_id: tripId, traveler_id })));
  if (error) throw new Error(error.message);
}

