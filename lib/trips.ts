/**
 * F3: a checklist item should link to the real booking once made, so the
 * checklist does not become a second, disconnected source of truth. Linking
 * marks it done in the same step, since that is what linking means.
 */
export async function linkChecklistItemToTripItem(
  itemId: string,
  tripItemId: string
): Promise<ChecklistItem> {
  const { data, error } = await supabase
    .from('trip_checklist_items')
    .update({ linked_trip_item_id: tripItemId, status: 'done' })
    .eq('id', itemId)
    .select(CHECKLIST_COLUMNS)
    .single();
  if (error) throw new Error(error.message);
  return data as ChecklistItem;
}

/**
 * Run F3's automatic passport check and reflect the result on the checklist.
 *
 * Auto items are upserted rather than appended: the unique index on
 * (trip_id, source, label) means re-running on every save updates rather than
 * duplicating. Issues that have since been resolved have their auto items
 * removed, so a fixed problem stops nagging.
 */
export async function syncPassportChecklist(
  tripId: string,
  issues: readonly ValidityIssue[]
): Promise<void> {
  const wanted = issues.map(checklistLabelForIssue);

  const { data: existing } = await supabase
    .from('trip_checklist_items')
    .select('id, label')
    .eq('trip_id', tripId)
    .eq('source', 'auto-passport');

  const existingRows = (existing ?? []) as { id: string; label: string }[];

  const stale = existingRows.filter((r) => !wanted.includes(r.label));
  if (stale.length > 0) {
    await supabase
      .from('trip_checklist_items')
      .delete()
      .in('id', stale.map((r) => r.id));
  }

  const have = new Set(existingRows.map((r) => r.label));
  const toAdd = wanted.filter((label) => !have.has(label));
  if (toAdd.length > 0) {
    const { error } = await supabase.from('trip_checklist_items').insert(
      toAdd.map((label) => ({
        trip_id: tripId,
        label,
        category: 'documents' as const,
        source: 'auto-passport' as const,
      }))
    );
    if (error) console.warn('could not add passport checklist items:', error.message);
  }
}

/**
 * The whole check in one call: read the attendees' passports, apply the rule,
 * and update the checklist. Returns the issues so the UI can also say something
 * immediately, which F3 asks for on save.
 */
export async function runPassportCheck(
  tripId: string,
  attendees: readonly { id: string; name: string }[],
  tripEndDate: string | null
): Promise<ValidityIssue[]> {
  if (attendees.length === 0 || !tripEndDate) return [];

  const { data, error } = await supabase
    .from('documents')
    .select('id, traveler_id, type, expiry_date, country')
    .in('traveler_id', attendees.map((a) => a.id));

  if (error) throw new Error(error.message);

  const issues = checkPassportValidity({
    attendees,
    documents: (data ?? []) as never,
    tripEndDate,
  });

  await syncPassportChecklist(tripId, issues);
  return issues;
}

