async function seedDefaultChecklist(tripId: string): Promise<void> {
  const { error } = await supabase.from('trip_checklist_items').insert(
    DEFAULT_CHECKLIST_ITEMS.map((d) => ({
      trip_id: tripId,
      label: d.label,
      category: d.category,
      source: 'default' as const,
    }))
  );
  // A seeding failure must not lose the trip that was just created.
  if (error) console.warn('could not seed default checklist:', error.message);
}

